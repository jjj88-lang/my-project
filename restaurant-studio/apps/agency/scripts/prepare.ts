/**
 * Runs before dev, build, typecheck and test.
 *
 * Writes src/generated/secret.ts: a random secret that signs the contact form's tokens.
 * The file is gitignored and never reaches the browser. A production build always gets a
 * fresh one (--fresh-secret). Setting FORM_SECRET (32+ characters) in the environment
 * overrides it, which is only needed if you want tokens to survive a redeploy.
 */
import { randomBytes } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const GENERATED_DIR = path.join(ROOT, "src", "generated");
const SECRET_FILE = path.join(GENERATED_DIR, "secret.ts");

const freshSecret = process.argv.includes("--fresh-secret");

fs.mkdirSync(GENERATED_DIR, { recursive: true });

if (freshSecret || !fs.existsSync(SECRET_FILE)) {
  fs.writeFileSync(
    SECRET_FILE,
    [
      "// AUTO-GENERATED by scripts/prepare.ts. Server-only. Regenerated on every production build.",
      `export const BUILD_SECRET = "${randomBytes(32).toString("hex")}";`,
      "",
    ].join("\n"),
  );
}
